import {createDurableJsonIO} from "../api/durable-json";
import {createAgentReadOnlyAuditHistory} from "../agent-readonly-audit";
import {logger} from "../logger";
import type {FloatingBallUiController, FloatingBallSurface} from "../floating-ball-ui";
import type {createFloatingBallPanelController} from "../floating-ball-panel";
import {HOME_ACCENTS, type ISpeedSwitchHost, type Tab} from "./plugin-types";

export function initRuntimeState(host: ISpeedSwitchHost): void {
    if (host.snippetStudioDialog === undefined) host.snippetStudioDialog = null;
    if (host.snippetStackDialog === undefined) host.snippetStackDialog = null;
    if (host.lastEditorSelection === undefined) host.lastEditorSelection = null;
    if (host.disposeSelectionObserver === undefined) host.disposeSelectionObserver = null;
    if (host.disposeRaikiriBridge === undefined) host.disposeRaikiriBridge = null;
    if (host.snippetStudioSession === undefined) host.snippetStudioSession = {draft: null, baseline: null};
    if (host.lastPlatformSurface === undefined) host.lastPlatformSurface = "switcher";
    if (host.lastPlatformContext === undefined) host.lastPlatformContext = null;
    if (host.switcherScene === undefined) host.switcherScene = null;
    if (host.platformSwitcherDialog === undefined) host.platformSwitcherDialog = null;
    if (host.mobileSwitcherDialog === undefined) host.mobileSwitcherDialog = null;
    if (host.workbenchDialog === undefined) host.workbenchDialog = null;
    if (host.platformGuideDialog === undefined) host.platformGuideDialog = null;
    if (host.settingsDialog === undefined) host.settingsDialog = null;
    if (host.workbenchResumeEditing === undefined) host.workbenchResumeEditing = false;
    if (host.snippetObjectsCache === undefined) host.snippetObjectsCache = null;
    if (host.snippetObjectsGeneration === undefined) host.snippetObjectsGeneration = 0;
    if (host.snippetObjectsInFlight === undefined) host.snippetObjectsInFlight = null;
    if (host.workspaceRuntimeDiagnostics === undefined) host.workspaceRuntimeDiagnostics = null;
    if (host.agentReadOnlyAuditHistory === undefined) host.agentReadOnlyAuditHistory = createAgentReadOnlyAuditHistory(8);
    if (host.storageMigrationReport === undefined) host.storageMigrationReport = null;
    if (host.storageSchemaDowngradeFrom === undefined) host.storageSchemaDowngradeFrom = null;
    if (host.pendingSchemaStamp === undefined) host.pendingSchemaStamp = false;
    if (host.dataChangeReloadInFlight === undefined) host.dataChangeReloadInFlight = false;
    if (host.dataChangeReloadQueued === undefined) host.dataChangeReloadQueued = false;
    if (host.activeAgentSearchControllers === undefined) host.activeAgentSearchControllers = new Set<AbortController>();
    if (host.activeDocumentSetRestoreControllers === undefined) host.activeDocumentSetRestoreControllers = new Set<AbortController>();
    if (host.recentPaletteActions === undefined) host.recentPaletteActions = [];
    if (host.recentSearchQueries === undefined) host.recentSearchQueries = [];
    if (host.switcherRefreshers === undefined) host.switcherRefreshers = new Set<() => void>();
    if (host.homeModuleChangeListeners === undefined) host.homeModuleChangeListeners = new Set<() => void>();
    if (host.switcherRefreshFrame === undefined) host.switcherRefreshFrame = null;
    if (host.switcherRefreshFrameCancel === undefined) host.switcherRefreshFrameCancel = null;
    if (host.sidebarElement === undefined) host.sidebarElement = null;
    if (host.sidebarHistoryDropdownDispose === undefined) host.sidebarHistoryDropdownDispose = null;
    if (host.sidebarSearchFilterDispose === undefined) host.sidebarSearchFilterDispose = null;
    if (host.sidebarResizeObserver === undefined) host.sidebarResizeObserver = null;
    if (host.sidebarIconObserver === undefined) host.sidebarIconObserver = null;
    if (host.sidebarIconFrameCancel === undefined) host.sidebarIconFrameCancel = null;
    if (host.recentOpenSnapshot === undefined) host.recentOpenSnapshot = new Map<string, string>();
    if (host.recentClosedSyncTimer === undefined) host.recentClosedSyncTimer = null;
    if (host.lifecycleGeneration === undefined) host.lifecycleGeneration = 0;
    if (host.isUnloading === undefined) host.isUnloading = false;
    if (host.syncing === undefined) host.syncing = false;
    if (host.syncDepth === undefined) host.syncDepth = 0;
    if (host.syncRefreshPending === undefined) host.syncRefreshPending = false;
    if (host.syncWatchdogTimer === undefined) host.syncWatchdogTimer = null;
    if (host.globalEventHandlers === undefined) host.globalEventHandlers = null;
    if (host.favCollapsed === undefined) host.favCollapsed = new Set<string>();
    if (host.fabElement === undefined) host.fabElement = null;
    if (host.floatingBallUi === undefined) host.floatingBallUi = null;
    if (host.floatingBallUis === undefined) host.floatingBallUis = new Map<FloatingBallSurface, FloatingBallUiController>();
    if (host.floatingBallPanels === undefined) host.floatingBallPanels = new Map<FloatingBallSurface, ReturnType<typeof createFloatingBallPanelController>>();
    if (host.fabModalDepth === undefined) host.fabModalDepth = 0;
    if (host.cardTabs === undefined) host.cardTabs = new WeakMap<HTMLElement, Tab>();
    if (host.cardMenuHandlers === undefined) host.cardMenuHandlers = new WeakMap<HTMLElement, {
        onActivate: (tab: Tab) => void,
        onTogglePin: (tab: Tab, card: HTMLElement) => void,
        onToggleFav: (tab: Tab, card: HTMLElement) => void,
        onCloseTab: (tab: Tab, card: HTMLElement) => void,
    }>();
    if (host.activeHistoryMenu === undefined) host.activeHistoryMenu = null;
    if (host.historyDropdownClosers === undefined) host.historyDropdownClosers = new WeakMap<HTMLElement, {close: () => void; dispose: () => void}>();
    if (host.historyDropdownCloseSet === undefined) host.historyDropdownCloseSet = new Set<() => void>();
    if (host.externalCommandPolicy === undefined) host.externalCommandPolicy = {enabled: false, allowNavigation: false, allowWrites: false};
    if (host.externalJsonIO === undefined) host.externalJsonIO = createDurableJsonIO();
    if (host.groupOperationBusy === undefined) host.groupOperationBusy = false;
    if (host.onAgentCapFail === undefined) host.onAgentCapFail = (error: unknown, spec: {name?: string}) => logger.warn(`register Agent capability ${spec?.name || "unknown"} fail`, error);
    if (host.ecosystemDisposer === undefined) host.ecosystemDisposer = null;
    if (host.ecosystemUnsubscribers === undefined) host.ecosystemUnsubscribers = [];
    if (host.breadcrumbButtonId === undefined) host.breadcrumbButtonId = "";
    if (host.settingsCache === undefined) host.settingsCache = null;
    if (host.settingsUndoRecorder === undefined) host.settingsUndoRecorder = null;
    if (host.settingsUndoSuppress === undefined) host.settingsUndoSuppress = false;
    if (host.lastSaveOutcome === undefined) host.lastSaveOutcome = {};
    if (host.settingsSceneReloader === undefined) host.settingsSceneReloader = null;
    if (host.dataMemos === undefined) host.dataMemos = new Map<string, {raw: unknown; items: any[]}>();
    if (host.cardSearchIndex === undefined) host.cardSearchIndex = new WeakMap<HTMLElement, {rawTitle: string; rawPath: string; rawPlugin?: string; title: string; path: string; plugin?: string}>();
    if (host.settingTitleSeq === undefined) host.settingTitleSeq = 0;
    if (host.commandCollapsedGroups === undefined) host.commandCollapsedGroups = new Set<string>();
    if (host.sessionMarks === undefined) host.sessionMarks = new Map<string, number>();
    if (host.relatedContentCache === undefined) host.relatedContentCache = new Map();
    if (host.relatedContentRequestGenerations === undefined) host.relatedContentRequestGenerations = new Map<string, number>();
    if (host.relatedSwrStore === undefined) host.relatedSwrStore = new Map();
    if (host.homeModuleOpens === undefined) host.homeModuleOpens = new Map<string, () => void>();
    if (host.homeThirdPartyIds === undefined) host.homeThirdPartyIds = new Set<string>();
    if (host.homePanelSnapshots === undefined) host.homePanelSnapshots = new Map<string, {snapshot: any; at: number}>();
    if (host.homeBuiltinAdapterIds === undefined) host.homeBuiltinAdapterIds = new Set<string>();
    if (host.homeAccents === undefined) host.homeAccents = HOME_ACCENTS;
    if (host.activeIconPickerCleanup === undefined) host.activeIconPickerCleanup = null;
    if (host.updatedMapCache === undefined) host.updatedMapCache = null;
    if (host.docScrollMemory === undefined) host.docScrollMemory = new Map<string, number>();
    if (host.lastPickedByQuery === undefined) host.lastPickedByQuery = new Map<string, string>();
    if (host.jumpBackStack === undefined) host.jumpBackStack = [];
    if (host.jumpForwardStack === undefined) host.jumpForwardStack = [];
    if (host.suppressJumpCapture === undefined) host.suppressJumpCapture = false;
    if (host.groupCollapseState === undefined) host.groupCollapseState = new Set<string>();
    if (host.createdByIdCache === undefined) host.createdByIdCache = {};
    if (host.notebookListCache === undefined) host.notebookListCache = null;
    if (host.rootNotebookCache === undefined) host.rootNotebookCache = {};
    if (host.groupFlowObserver === undefined) host.groupFlowObserver = null;
    if (host.homeRefreshTimer === undefined) host.homeRefreshTimer = 0;
    if (host.sidebarRefreshTimer === undefined) host.sidebarRefreshTimer = 0;
    if (host.pendingThumbScales === undefined) host.pendingThumbScales = [];
    if (host.thumbScaleFramePending === undefined) host.thumbScaleFramePending = false;
    if (host.thumbApiActive === undefined) host.thumbApiActive = 0;
    if (host.thumbApiQueue === undefined) host.thumbApiQueue = [];
    if (host.thumbApiControllers === undefined) host.thumbApiControllers = new Map<HTMLElement, AbortController>();
}
